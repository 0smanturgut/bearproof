const glyph = (ch) => G[ch] || G[' '];

/** Width in pixels of `str` at `scale` (1 px gap between glyphs). */
export function measure(str, scale) {
    let w = 0;
    for (const ch of String(str).toUpperCase()) w += (glyph(ch)[0].length + 1) * scale;
    return Math.max(0, w - scale);
}

/** Draw `str` with its top-left at (x, y). Returns the width drawn. */
export function text(r, str, x, y, scale, hex) {
    let cx = x;
    for (const ch of String(str).toUpperCase()) {
        const g = glyph(ch);
        for (let gy = 0; gy < g.length; gy++) {
            const row = g[gy];
            for (let gx = 0; gx < row.length; gx++) {
                if (row[gx] !== '#') continue;
                // merge horizontal runs into one rect
                let run = 1;
                while (row[gx + run] === '#') run++;
                r.rect(cx + gx * scale, y + gy * scale, run * scale, scale, hex);
                gx += run - 1;
            }
        }
        cx += (g[0].length + 1) * scale;
    }
    return cx - x - scale;
}
